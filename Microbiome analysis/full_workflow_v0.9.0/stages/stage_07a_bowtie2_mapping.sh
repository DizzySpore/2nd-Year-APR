#!/bin/bash
################################################################################
# STAGE 07A: Bowtie2 - Read mapping to assembly for coverage calculation
################################################################################
#
# Input variables (from SLURM template):
#   - SAMPLE        : Sample name
#   - NUM_THREADS   : Number of CPU threads
#   - ASSEMBLY_FILE : Path to MEGAHIT final contigs
#   - KNEADDATA_OUT : Directory containing decontaminated paired reads
#   - MAPPING_DIR   : Output directory for BAM files and coverage tables
#   - STATUS_DIR    : Path to status directory
#
# Output:
#   - Bowtie2 index  : ${MAPPING_DIR}/index/${SAMPLE}_assembly.*
#   - Sorted BAM     : ${MAPPING_DIR}/${SAMPLE}.sorted.bam
#   - BAM index      : ${MAPPING_DIR}/${SAMPLE}.sorted.bam.bai
#   - Depth file     : ${MAPPING_DIR}/${SAMPLE}_depth.txt
#   - Coverage table : ${MAPPING_DIR}/${SAMPLE}_coverage.tsv
#   - ${STATUS_DIR}/${SAMPLE}.resume updated to STAGE_07B
#
# Note:
#   - The bowtie2 index, sorted BAM, depth file and coverage table are all
#     required by the four binners in STAGE_07B
#   - Depth file is generated by jgi_summarize_bam_contig_depths (MetaBAT2
#     utility) and is compatible with MetaBAT2 and COMEbin
#   - Coverage table is generated by cutting columns from the depth file
#     into the format required by CONCOCT
#   - The unsorted BAM is removed after sorting to save storage
#   - Automatically detects whether Kneaddata produced .fastq or .fastq.gz
#     and feeds the correct files to Bowtie2 (no temporary decompression)
#
################################################################################

echo "$(date): [STAGE 07A] Starting bowtie2 read mapping for ${SAMPLE}..."
echo "  Assembly : ${ASSEMBLY_FILE}"
echo "  Output   : ${MAPPING_DIR}"

INDEX_DIR="${MAPPING_DIR}/index"
mkdir -p "${INDEX_DIR}"

# ----------------------------------------------------------------------
# Detect whether Kneaddata reads are gzipped or plain FASTQ
# ----------------------------------------------------------------------
R1_CANDIDATE="${KNEADDATA_OUT}/out.${SAMPLE}.R1_kneaddata_paired_1.fastq"
R2_CANDIDATE="${KNEADDATA_OUT}/out.${SAMPLE}.R1_kneaddata_paired_2.fastq"
R1_GZ="${R1_CANDIDATE}.gz"
R2_GZ="${R2_CANDIDATE}.gz"

if [[ -f "${R1_GZ}" && -f "${R2_GZ}" ]]; then
    echo "$(date): [STAGE 07A] Found gzipped reads – using them directly (no decompression)."
    READ1="${R1_GZ}"
    READ2="${R2_GZ}"
elif [[ -f "${R1_CANDIDATE}" && -f "${R2_CANDIDATE}" ]]; then
    echo "$(date): [STAGE 07A] Found uncompressed reads."
    READ1="${R1_CANDIDATE}"
    READ2="${R2_CANDIDATE}"
else
    echo "$(date): [STAGE 07A] ERROR: neither .fastq nor .fastq.gz files found for ${SAMPLE}"
    echo "  Looked for:"
    echo "    ${R1_CANDIDATE}  /  ${R1_GZ}"
    echo "    ${R2_CANDIDATE}  /  ${R2_GZ}"
    exit 1
fi

echo "  Reads R1 : ${READ1}"
echo "  Reads R2 : ${READ2}"

conda activate bowtie2-env

# -- Build bowtie2 index from assembly ----------------------------------------
echo "$(date): [STAGE 07A] Building bowtie2 index..."
bowtie2-build \
    --threads ${NUM_THREADS} \
    "${ASSEMBLY_FILE}" \
    "${INDEX_DIR}/${SAMPLE}_assembly"
echo "$(date): [STAGE 07A] Bowtie2 index built."

# -- Map reads to assembly -----------------------------------------------------
echo "$(date): [STAGE 07A] Mapping decontaminated reads to assembly..."
bowtie2 \
    -x "${INDEX_DIR}/${SAMPLE}_assembly" \
    -1 "${READ1}" \
    -2 "${READ2}" \
    --threads ${NUM_THREADS} \
    --no-unal \
    -S "${MAPPING_DIR}/${SAMPLE}.sam"
echo "$(date): [STAGE 07A] Read mapping complete."

conda deactivate || true

# -- Convert SAM to sorted BAM -------------------------------------------------
conda activate samtools-env

echo "$(date): [STAGE 07A] Converting SAM to sorted BAM..."
samtools view \
    -bS \
    -@ ${NUM_THREADS} \
    "${MAPPING_DIR}/${SAMPLE}.sam" | \
samtools sort \
    -@ ${NUM_THREADS} \
    -o "${MAPPING_DIR}/${SAMPLE}.sorted.bam"

# Index the sorted BAM
echo "$(date): [STAGE 07A] Indexing sorted BAM..."
samtools index "${MAPPING_DIR}/${SAMPLE}.sorted.bam"

# Log basic mapping statistics
echo "$(date): [STAGE 07A] Mapping statistics:"
samtools flagstat "${MAPPING_DIR}/${SAMPLE}.sorted.bam"

conda deactivate || true

# Remove intermediate SAM file to save storage
echo "$(date): [STAGE 07A] Removing intermediate SAM file..."
rm -f "${MAPPING_DIR}/${SAMPLE}.sam"

# -- Generate depth and coverage files ----------------------------------------
conda activate metabat2-env

# Depth file — required by MetaBAT2 and COMEbin
echo "$(date): [STAGE 07A] Generating contig depth file..."
jgi_summarize_bam_contig_depths \
    --outputDepth "${MAPPING_DIR}/${SAMPLE}_depth.txt" \
    "${MAPPING_DIR}/${SAMPLE}.sorted.bam"

conda deactivate || true

# Coverage table — required by CONCOCT
# CONCOCT expects a TSV with contig IDs and mean coverage per sample
# This is derived from the depth file by extracting contig name and mean depth
echo "$(date): [STAGE 07A] Generating CONCOCT coverage table..."
awk 'NR>1 {print $1"\t"$3}' "${MAPPING_DIR}/${SAMPLE}_depth.txt" \
    > "${MAPPING_DIR}/${SAMPLE}_coverage.tsv"

echo "$(date): [STAGE 07A] Coverage files generated."
echo "  Depth file     : ${MAPPING_DIR}/${SAMPLE}_depth.txt"
echo "  Coverage table : ${MAPPING_DIR}/${SAMPLE}_coverage.tsv"
echo "  Sorted BAM     : ${MAPPING_DIR}/${SAMPLE}.sorted.bam"

echo "STAGE_07B" > "${STATUS_DIR}/${SAMPLE}.resume"
echo "$(date): [STAGE 07A] Bowtie2 mapping complete."